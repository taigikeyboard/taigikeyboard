import Foundation

/// PhahTaigi 鍵盤佈局映射定義
///
/// 此佈局將常用標點符號放置在更容易觸及的位置，
/// 專為台語輸入優化，減少切換鍵盤的頻率。
///
/// ## 按鍵映射規則
///
/// **第一列（數字列下方）**
/// - q → !（驚嘆號）
/// - w → ?（問號）
/// - e~p 保持不變
///
/// **第二列**
/// - a~l 保持不變
/// - l 右邊位置 → -（連字符，不受 inputMode 影響）
///
/// **第三列（Shift 右側）**
/// - z → ,（逗號）
/// - x → .（句號）
/// - c~m 保持不變
///
/// ## 設計理念
///
/// 1. **高頻符號前置**：!, ?, ,, . 是台語書寫常用符號
/// 2. **減少模式切換**：避免頻繁切換到 numeric/symbolic 鍵盤
/// 3. **連字符固定**：- 在 l 右邊，方便台語羅馬字複合詞輸入
/// 4. **保持肌肉記憶**：僅替換低頻字母，不影響主要輸入流程
enum PhahTaigiMapping {
    /// 第一列按鍵佈局（q→!, w→?，其餘保持）
    static let firstRow = "!?ertyuiop"

    /// 第二列按鍵佈局（l 右邊固定為連字符）
    static let secondRow = "asdfghjkl-"

    /// 第三列字母部分（z→,, x→.，其餘保持）
    static let thirdRowLetters = ",.cvbnm"
}
